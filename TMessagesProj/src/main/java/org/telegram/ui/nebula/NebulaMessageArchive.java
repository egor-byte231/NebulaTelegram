package org.telegram.ui.nebula;

import android.content.Context;
import android.content.SharedPreferences;
import org.json.JSONArray;
import org.json.JSONObject;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.ArrayBlockingQueue;
import java.util.concurrent.ThreadPoolExecutor;
import java.util.concurrent.TimeUnit;

/** Opt-in, on-device message snapshot store. Does not recover messages never received. */
public final class NebulaMessageArchive {
    private static final java.util.concurrent.atomic.AtomicLong EPOCH = new java.util.concurrent.atomic.AtomicLong();
    private static final String PREF = "nebula_message_archive_v1";
    private static final String KEY = "entries";
    private static final int DEFAULT_MAX_ENTRIES = 2000;
    private static final String SETTINGS = "nebula_archive_settings_v1";
    private static final String RETENTION_DAYS = "retention_days";
    private static final String ENTRY_LIMIT = "entry_limit";
    // Stable keys generated by NebulaFeaturesActivity: archive_0=deleted, archive_1=edits.
    private static final String ARCHIVE_DELETED = "archive_0";
    private static final String ARCHIVE_EDITS = "archive_1";
    public static boolean capturesDeleted(Context c) {
        return c.getSharedPreferences("nebula_features_v1", Context.MODE_PRIVATE).getBoolean(ARCHIVE_DELETED, false);
    }
    public static boolean capturesEdits(Context c) {
        return c.getSharedPreferences("nebula_features_v1", Context.MODE_PRIVATE).getBoolean(ARCHIVE_EDITS, false);
    }
    public static boolean isEnabled(Context c) { return capturesDeleted(c) || capturesEdits(c); }
    private static final String PAUSED = "paused";
    private NebulaMessageArchive() {}
    /** Explicit local pause: no new snapshots are collected while paused. */
    public static boolean isPaused(Context c) {
        return c.getSharedPreferences(SETTINGS, Context.MODE_PRIVATE).getBoolean(PAUSED, false);
    }
    public static void setPaused(Context c, boolean paused) {
        c.getSharedPreferences(SETTINGS, Context.MODE_PRIVATE).edit().putBoolean(PAUSED, paused).commit();
    }
    /** Read the account ID from a locally generated archive key. */
    public static int accountOf(Entry e) {
        if (e == null || e.chatKey == null || !e.chatKey.startsWith("telegram:")) return -1;
        int end = e.chatKey.indexOf(':', 9);
        if (end < 0) return -1;
        try { return Integer.parseInt(e.chatKey.substring(9, end)); }
        catch (NumberFormatException ex) { return -1; }
    }
    public static synchronized int clearAccount(Context c, int account) {
        EPOCH.incrementAndGet();
        List<Entry> entries = load(c);
        int before = entries.size();
        for (int i = entries.size() - 1; i >= 0; i--)
            if (accountOf(entries.get(i)) == account) entries.remove(i);
        int removed = before - entries.size();
        return removed > 0 && save(c, entries) ? removed : 0;
    }
    // Bound background work so loading a long chat never blocks the UI or creates unlimited tasks.
    private static final ThreadPoolExecutor WRITER = new ThreadPoolExecutor(
            1, 1, 0L, TimeUnit.MILLISECONDS,
            new ArrayBlockingQueue<Runnable>(256),
            new ThreadPoolExecutor.DiscardPolicy());

    /** Capture received text asynchronously; opt-in checks are performed again in capture(). */
    public static void captureAsync(Context context, int account, long dialogId, long messageId, String text) {
        if (context == null || text == null || text.length() == 0 || text.length() > 16384 || messageId <= 0) return;
        if (isPaused(context)) return;
        Context app = context.getApplicationContext();
        if (!isEnabled(app)) return;
        final String snapshot = text;
        final long epoch = EPOCH.get();
        WRITER.execute(() -> { if (epoch == EPOCH.get()) capture(app, account, dialogId, messageId, snapshot); });
    }

    public static final class Entry {
        public final String chatKey;
        public final long messageId;
        public final long capturedAt;
        public final boolean deleted;
        public final ArrayList<String> versions;
        Entry(String chatKey, long messageId, long capturedAt, boolean deleted, ArrayList<String> versions) {
            this.chatKey=chatKey; this.messageId=messageId; this.capturedAt=capturedAt;
            this.deleted=deleted; this.versions=versions;
        }
        JSONObject toJson() throws Exception {
            JSONObject o=new JSONObject();o.put("chat",chatKey);o.put("id",messageId);
            o.put("at",capturedAt);o.put("deleted",deleted);
            JSONArray v=new JSONArray();for(String s:versions)v.put(s);o.put("versions",v);return o;
        }
    }
    public static int retentionDays(Context c) {
        return c.getSharedPreferences(SETTINGS,Context.MODE_PRIVATE).getInt(RETENTION_DAYS,30);
    }
    public static int entryLimit(Context c) {
        return c.getSharedPreferences(SETTINGS,Context.MODE_PRIVATE).getInt(ENTRY_LIMIT,2000);
    }
    public static void setRetentionDays(Context c,int days) {
        if(days!=7 && days!=30 && days!=90 && days!=0) throw new IllegalArgumentException("days");
        c.getSharedPreferences(SETTINGS,Context.MODE_PRIVATE).edit().putInt(RETENTION_DAYS,days).apply();
        prune(c);
    }
    public static void setEntryLimit(Context c,int limit) {
        if(limit!=250 && limit!=1000 && limit!=2000) throw new IllegalArgumentException("limit");
        c.getSharedPreferences(SETTINGS,Context.MODE_PRIVATE).edit().putInt(ENTRY_LIMIT,limit).apply();
        prune(c);
    }
    /** Enforce user retention and entry count even for archives created by older versions. */
    public static synchronized int prune(Context c) {
        List<Entry> entries=load(c);
        int before=entries.size();
        int days=retentionDays(c);
        long cutoff=days==0?Long.MIN_VALUE:System.currentTimeMillis()-days*86400000L;
        for(int i=entries.size()-1;i>=0;i--)if(entries.get(i).capturedAt<cutoff)entries.remove(i);
        int limit=entryLimit(c);
        while(entries.size()>limit)entries.remove(0);
        int removed=before-entries.size();
        if(removed>0)save(c,entries);
        return removed;
    }
    private static String key(int account,long dialogId) {return "telegram:"+account+":"+dialogId;}
    private static SharedPreferences pref(Context c) {return c.getSharedPreferences(PREF,Context.MODE_PRIVATE);}
    public static List<Entry> load(Context c) {
        ArrayList<Entry> out=new ArrayList<>();
        try {
            JSONArray a=new JSONArray(NebulaSecureArchive.read(c));
            for(int i=0;i<a.length();i++) {
                JSONObject o=a.optJSONObject(i);if(o==null)continue;
                JSONArray arr=o.optJSONArray("versions");ArrayList<String> versions=new ArrayList<>();
                if(arr!=null)for(int j=0;j<arr.length();j++)versions.add(arr.optString(j,""));
                out.add(new Entry(o.optString("chat"),o.optLong("id"),o.optLong("at"),o.optBoolean("deleted"),versions));
            }
        }catch(Exception error){throw new IllegalStateException("Unable to decrypt local archive", error);}return out;
    }
    private static boolean save(Context c,List<Entry> entries) {
        JSONArray a=new JSONArray();try {for(Entry e:entries)a.put(e.toJson());}
        catch(Exception ex){return false;}
        return NebulaSecureArchive.write(c, a.toString());
    }
    /** Captures only content actually supplied to this client, when user opted in. */
    public static synchronized boolean capture(Context c,int account,long dialogId,long messageId,String text) {
        if(text==null||text.length()>16384||text.isEmpty()||isPaused(c))return false;
        if (!isEnabled(c)) return false;
        String chat=key(account,dialogId);
        try {JSONObject rule=new JSONObject(c.getSharedPreferences("nebula_chat_rules_v1",Context.MODE_PRIVATE).getString(chat,"{}"));
            if(rule.optBoolean("exclude",false))return false;
        }catch(Exception ignored){}
        List<Entry> entries=load(c);
        int days=retentionDays(c);
        long cutoff=days==0?Long.MIN_VALUE:System.currentTimeMillis()-days*86400000L;
        for(int i=entries.size()-1;i>=0;i--)if(entries.get(i).capturedAt<cutoff)entries.remove(i);
        for(int i=0;i<entries.size();i++) {
            Entry e=entries.get(i);
            if(e.messageId==messageId&&chat.equals(e.chatKey)) {
                if(e.versions.size()>0&&text.equals(e.versions.get(e.versions.size()-1))) {
                    trimToLimit(c, entries);
                    return save(c, entries);
                }
                ArrayList<String> versions=new ArrayList<>(e.versions);
                if(!capturesEdits(c))versions.clear();
                versions.add(text);while(versions.size()>12)versions.remove(0);
                entries.set(i,new Entry(chat,messageId,e.capturedAt,e.deleted,versions));
                trimToLimit(c, entries);
                return save(c,entries);
            }
        }
        ArrayList<String> versions=new ArrayList<>();versions.add(text);
        entries.add(new Entry(chat,messageId,System.currentTimeMillis(),false,versions));
        trimToLimit(c,entries);
        return save(c,entries);
    }
    /** Apply entry limit only after updating an existing message, to avoid evicting it first. */
    private static void trimToLimit(Context c, List<Entry> entries) {
        while (entries.size() > entryLimit(c)) entries.remove(0);
    }

    /** Explicit, user-initiated JSON export of locally retained snapshots. */
    public static synchronized String exportJson(Context c) throws Exception {
        JSONObject document = new JSONObject();
        document.put("format", "nebula-message-archive");
        document.put("version", 1);
        document.put("exportedAt", System.currentTimeMillis());
        JSONArray snapshots = new JSONArray();
        for (Entry e : load(c)) snapshots.put(e.toJson());
        document.put("entries", snapshots);
        return document.toString(2);
    }

    public static final class Stats {
        public final int messages, deleted, edited, versions, chats;
        Stats(int messages, int deleted, int edited, int versions, int chats) {
            this.messages = messages; this.deleted = deleted; this.edited = edited;
            this.versions = versions; this.chats = chats;
        }
    }
    public static synchronized Stats stats(Context c) {
        List<Entry> entries = load(c);
        int deleted = 0, edited = 0, versions = 0;
        java.util.HashSet<String> chats = new java.util.HashSet<>();
        for (Entry e : entries) {
            if (e.deleted) deleted++;
            if (e.versions.size() > 1) edited++;
            versions += e.versions.size();
            chats.add(e.chatKey);
        }
        return new Stats(entries.size(), deleted, edited, versions, chats.size());
    }

    /** Queue observed deletion after earlier snapshot writes on the same worker. */
    public static void markDeletedAsync(Context context, int account, long dialogId, long messageId) {
        if (context == null || messageId <= 0 || isPaused(context)) return;
        Context app = context.getApplicationContext();
        if (!capturesDeleted(app)) return;
        final long epoch = EPOCH.get();
        WRITER.execute(() -> {
            if (epoch == EPOCH.get() && !isPaused(app) && capturesDeleted(app)) {
                markDeleted(app, account, dialogId, messageId);
            }
        });
    }

    /** Delete all locally captured snapshots belonging to one chat. */
    public static synchronized int clearChat(Context context, String chatKey) {
        EPOCH.incrementAndGet();
        List<Entry> entries = load(context);
        int before = entries.size();
        for (int i = entries.size() - 1; i >= 0; i--) {
            if (entries.get(i).chatKey.equals(chatKey)) entries.remove(i);
        }
        int removed = before - entries.size();
        return removed > 0 && save(context, entries) ? removed : 0;
    }

    /** Only marks a deletion observed by this client. */
    public static synchronized boolean markDeleted(Context c,int account,long dialogId,long messageId) {
        List<Entry> entries=load(c);String chat=key(account,dialogId);
        for(int i=0;i<entries.size();i++) {
            Entry e=entries.get(i);if(e.messageId==messageId&&chat.equals(e.chatKey)) {
                entries.set(i,new Entry(e.chatKey,e.messageId,e.capturedAt,true,e.versions));return save(c,entries);
            }
        }return false;
    }
    public static synchronized boolean clear(Context c){
        // Stop future background snapshots until the user explicitly resumes archiving.
        setPaused(c, true);
        return NebulaSecureArchive.clear(c);
    }
    public static synchronized boolean delete(Context c,String chat,long messageId) {
        List<Entry> entries=load(c);boolean changed=false;
        for(int i=entries.size()-1;i>=0;i--)if(entries.get(i).chatKey.equals(chat)&&entries.get(i).messageId==messageId){entries.remove(i);changed=true;}
        return changed&&save(c,entries);
    }
}
